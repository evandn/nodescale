import type { SignerKey } from "@nodescale/protocol";
import { SERVER_TAG } from "./tags.ts";

/** Where gate binaries come from; configured on the console (see /api/me). */
export interface GateRelease {
  repo: string; // e.g. "evandn/nodescale"
  version: string; // a tag such as "v0.2.0", or "latest"
  sha256: { amd64?: string; arm64?: string };
  /** Optional mirror serving nodescale-gate-linux-<arch> and SHA256SUMS. */
  baseUrl?: string;
}

export interface InstallOptions {
  serverName: string;
  rpId: string;
  origin: string;
  signers: SignerKey[];
  release: GateRelease;
  /** One-time Tailscale auth key; omit for a device already on the tailnet. */
  tailscaleAuthKey?: string;
  cloudflareTunnelToken?: string;
  maxSessionSeconds?: number;
}

function shq(s: string) {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

function header(title: string, lines: string[]) {
  return `#!/bin/sh
# ${title} — generated by nodescale ${new Date().toISOString()}
${lines.map((l) => (l ? `# ${l}` : "#")).join("\n")}
set -eu
umask 022

[ "$(id -u)" = 0 ] || { echo "Please run as root (sudo sh $0)" >&2; exit 1; }
`;
}

/**
 * Downloads the gate for this architecture and verifies it against a pinned
 * SHA-256 (when the console is configured with one) or the release's
 * SHA256SUMS file, then installs it root:docker with the setgid bit.
 */
function installGateSnippet(r: GateRelease) {
  const base = r.baseUrl ? r.baseUrl.replace(/\/$/, "") : r.version === "latest" ? `https://github.com/${r.repo}/releases/latest/download` : `https://github.com/${r.repo}/releases/download/${r.version}`;
  return `
echo "==> nodescale-gate (${r.version})"
case "$(uname -m)" in
  x86_64|amd64) ARCH=amd64; PINNED=${shq(r.sha256.amd64 ?? "")} ;;
  aarch64|arm64) ARCH=arm64; PINNED=${shq(r.sha256.arm64 ?? "")} ;;
  *) echo "unsupported architecture $(uname -m)" >&2; exit 1 ;;
esac
getent group docker >/dev/null || groupadd --system docker
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
curl -fsSL ${r.baseUrl?.startsWith("http://") ? "" : "--proto '=https' --tlsv1.2 "}-o "$TMP/nodescale-gate" ${shq(base)}"/nodescale-gate-linux-$ARCH"
if [ -n "$PINNED" ]; then
  EXPECTED="$PINNED"
else
  curl -fsSL ${r.baseUrl?.startsWith("http://") ? "" : "--proto '=https' --tlsv1.2 "}-o "$TMP/SHA256SUMS" ${shq(base + "/SHA256SUMS")}
  EXPECTED="$(grep " nodescale-gate-linux-$ARCH\\$" "$TMP/SHA256SUMS" | cut -d' ' -f1)"
fi
ACTUAL="$(sha256sum "$TMP/nodescale-gate" | cut -d' ' -f1)"
if [ -z "$EXPECTED" ] || [ "$ACTUAL" != "$EXPECTED" ]; then
  echo "checksum mismatch for nodescale-gate: got $ACTUAL, expected \${EXPECTED:-<none>}" >&2
  exit 1
fi
install -m 0755 "$TMP/nodescale-gate" /usr/local/bin/nodescale-gate.new
chown root:docker /usr/local/bin/nodescale-gate.new
# setgid docker: only this binary, not the nodescale user, can reach the
# Docker socket (chmod after chown, which would clear the bit).
chmod 2755 /usr/local/bin/nodescale-gate.new
mv -f /usr/local/bin/nodescale-gate.new /usr/local/bin/nodescale-gate
`;
}

function secretsNotice(o: InstallOptions): string[] {
  const secrets = [o.tailscaleAuthKey && "a Tailscale auth key that expires in one hour", o.cloudflareTunnelToken && "a Cloudflare Tunnel token"].filter(Boolean);
  if (!secrets.length) return [];
  return [`This script contains secrets (${secrets.join(" and ")}).`, "Do not commit or share it.", ""];
}

/** Generates the bootstrap script a user runs once on a new server. */
export function installScript(o: InstallOptions): string {
  const config = {
    rpId: o.rpId,
    origins: [o.origin],
    signers: o.signers.map(({ id, alg, publicKey, role, label, user }) => ({ id, alg, publicKey, role, label, user })),
    policy: { maxSessionSeconds: o.maxSessionSeconds ?? 8 * 3600, containers: {} },
  };
  return (
    header(`nodescale bootstrap for "${o.serverName}"`, [
      "Run once as root:   sudo sh nodescale-install.sh",
      "",
      ...secretsNotice(o),
      "What it does (nothing here runs as a daemon for nodescale):",
      `  1. installs Docker and Tailscale if missing and enables Tailscale SSH${o.tailscaleAuthKey ? `, joining as ${SERVER_TAG}` : ""};`,
      "  2. installs nodescale-gate (checksum-verified) as root:docker setgid;",
      "  3. creates a locked-down \"nodescale\" user whose login shell is the gate",
      "     (no password, no home, no groups, so no shell and no Docker access);",
      "  4. writes the passkeys this server trusts to /etc/nodescale/gate.json;",
      "  5. creates the server identity key and verifies the installation.",
      ...(o.cloudflareTunnelToken ? ["  6. runs cloudflared for this server's Cloudflare Tunnel."] : []),
    ]) +
    `
TS_AUTHKEY=${shq(o.tailscaleAuthKey ?? "")}
TS_HOSTNAME=${shq(o.serverName)}
CF_TUNNEL_TOKEN=${shq(o.cloudflareTunnelToken ?? "")}

command -v curl >/dev/null 2>&1 || { apt-get update -qq && apt-get install -y -qq curl ca-certificates; }

echo "==> Docker"
if ! command -v docker >/dev/null 2>&1; then
  curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker >/dev/null 2>&1 || true

echo "==> Tailscale (with Tailscale SSH)"
if ! command -v tailscale >/dev/null 2>&1; then
  curl -fsSL https://tailscale.com/install.sh | sh
fi
if [ -n "$TS_AUTHKEY" ]; then
  tailscale up --authkey="$TS_AUTHKEY" --ssh --hostname="$TS_HOSTNAME" --advertise-tags=${SERVER_TAG}
else
  tailscale set --ssh
fi
${installGateSnippet(o.release)}
echo "==> Restricted nodescale user"
getent group nodescale >/dev/null || groupadd --system nodescale
if ! id nodescale >/dev/null 2>&1; then
  useradd --system --gid nodescale --home-dir /nonexistent --no-create-home --shell /usr/local/bin/nodescale-gate nodescale
fi
usermod --shell /usr/local/bin/nodescale-gate --groups "" nodescale
passwd -l nodescale >/dev/null 2>&1 || true

echo "==> Trusted passkeys"
install -d -m 2770 -o root -g docker /etc/nodescale /var/lib/nodescale
if [ -f /etc/nodescale/gate.json ]; then
  cp -p /etc/nodescale/gate.json "/etc/nodescale/gate.json.$(date +%s).bak"
fi
cat > /etc/nodescale/gate.json.new <<'NODESCALE_EOF'
${JSON.stringify(config, null, 2)}
NODESCALE_EOF
mv -f /etc/nodescale/gate.json.new /etc/nodescale/gate.json
nodescale-gate init >/dev/null
${
  o.cloudflareTunnelToken
    ? `
echo "==> Cloudflare Tunnel"
docker network inspect nodescale >/dev/null 2>&1 || docker network create --label io.nodescale.managed=true nodescale >/dev/null
docker rm -f cloudflared >/dev/null 2>&1 || true
docker run -d --name cloudflared --restart unless-stopped --network nodescale \\
  --read-only --cap-drop ALL --security-opt no-new-privileges \\
  --label io.nodescale.managed=true --log-opt max-size=10m --log-opt max-file=3 \\
  -e TUNNEL_TOKEN="$CF_TUNNEL_TOKEN" \\
  cloudflare/cloudflared:latest tunnel --no-autoupdate run >/dev/null
`
    : `
docker network inspect nodescale >/dev/null 2>&1 || docker network create --label io.nodescale.managed=true nodescale >/dev/null
`
}
echo
nodescale-gate check
echo
echo "==> Done. Compare this server identity with the one shown in nodescale before trusting it:"
nodescale-gate id
`
  );
}

/** Replaces the gate binary in place; configuration and identity are kept. */
export function upgradeScript(serverName: string, release: GateRelease): string {
  return (
    header(`nodescale-gate upgrade for "${serverName}"`, ["Run as root. Keeps /etc/nodescale and the server identity."]) +
    installGateSnippet(release) +
    `
nodescale-gate init >/dev/null
nodescale-gate check
nodescale-gate version
`
  );
}

/** Removes everything nodescale installed (Docker and Tailscale stay). */
export function uninstallScript(serverName: string): string {
  return (
    header(`nodescale uninstall for "${serverName}"`, [
      "Removes the nodescale user, gate binary, configuration and server identity.",
      "Docker, your containers and Tailscale are left untouched.",
    ]) +
    `
userdel nodescale 2>/dev/null || true
groupdel nodescale 2>/dev/null || true
rm -f /usr/local/bin/nodescale-gate
rm -rf /etc/nodescale /var/lib/nodescale
echo "nodescale removed. Optionally disable Tailscale SSH with: tailscale set --ssh=false"
`
  );
}

/** The tailnet policy fragment nodescale relies on. */
export const TAILNET_POLICY = `{
  "tagOwners": {
    "${SERVER_TAG}": ["autogroup:admin"],
    "tag:nodescale-relay": ["autogroup:admin"]
  },
  "grants": [
    // The relay may only reach servers' SSH port...
    { "src": ["tag:nodescale-relay"], "dst": ["${SERVER_TAG}"], "ip": ["tcp:22"] }
  ],
  "ssh": [
    // ...and only as the restricted "nodescale" user, whose login shell is
    // nodescale-gate.
    { "action": "accept", "src": ["tag:nodescale-relay"], "dst": ["${SERVER_TAG}"], "users": ["nodescale"] }
  ]
}`;
